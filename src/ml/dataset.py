SIC_LEAD_HOURS: Tuple[float, ...] = (24.0, 48.0, 72.0, 120.0, 168.0)

# Time-based split windows, in hours since the environment reference epoch (day of year 330,
# late November, the start of the expedition season).
#
# WHY TIME AND NOT RANDOM. Two samples drawn from the same analysis time share the same
# realisation of the floe and lead noise field, the same synoptic low and the same ice edge. A
# random split therefore puts near-duplicates of training rows into the test set, and the score
# measures memorisation of one weather realisation rather than generalisation to a new one. The
# same trap exists with real data, which is why operational ice services verify on withheld
# forecast cycles and never on withheld pixels.
#
# The gaps between windows are an embargo equal to the longest lead time. Without it, a training
# row with t0 near the end of the training window would have its *target* valid inside the
# validation window, so a field used for validation would already have been seen during fitting.
SIC_EMBARGO_H: float = 168.0
SIC_TRAIN_WINDOW_H: Tuple[float, float] = (0.0, 960.0)
SIC_VAL_WINDOW_H: Tuple[float, float] = (1128.0, 1440.0)
SIC_TEST_WINDOW_H: Tuple[float, float] = (1608.0, 1992.0)

# Points drawn per analysis time. Grouping samples into scenes is what makes generation fast:
# every physics call is vectorised over the whole scene, and the expensive semi-Lagrangian
# back-trajectory is walked once per (scene, lead) pair rather than once per row.
SIC_POINTS_PER_SCENE: int = 140

# Sampling domain. The northern limit sits well outside the ice edge so the model sees the
# open-water side of the marginal ice zone, which is where the 15 percent threshold decision
# actually gets made.
SIC_LAT_RANGE: Tuple[float, float] = (-75.0, -54.0)

# Finite-difference steps for the concentration gradient features, in degrees. These match the
# steps sea_ice.divergence uses, so the gradient features live on the same spatial scale as the
# divergence feature.
_H_LAT_DEG = 0.25
_H_LON_DEG = 0.5


@dataclass(frozen=True)
class SICDataset:
    """
    One time-window slice of the concentration-forecast problem.

    X, y and feature_names are the supervised triple. The remaining arrays are not features:
    they are the three baseline forecasts and the bookkeeping needed to score per lead time.
    Keeping the baselines out of X is deliberate. The learner has to earn its skill from the
    analysis fields; it is not handed the physics forecast to copy.
    """

    X: np.ndarray
    y: np.ndarray
    feature_names: Tuple[str, ...]
    lead_hours: np.ndarray
    t0_hours: np.ndarray
    persistence: np.ndarray
    climatology: np.ndarray
    physics: np.ndarray
    window_hours: Tuple[float, float]

    def __len__(self) -> int:
        return int(self.X.shape[0])

    def as_tuple(self) -> Tuple[np.ndarray, np.ndarray, Tuple[str, ...]]:
        """The (X, y, feature_names) triple, for callers that want only the supervised part."""
        return self.X, self.y, self.feature_names


def _ocean_points(rng: np.random.Generator, n: int) -> Tuple[np.ndarray, np.ndarray]:
    """
    Draw n ocean points inside the sampling domain.

    Rejection sampling against the coast distance field, which returns a negative distance on
    land. Oversampling by a generous factor keeps this to a single pass in practice.
    """
    lat_min, lat_max = SIC_LAT_RANGE
    cf = get_coast_field()
    lats: List[np.ndarray] = []
    lons: List[np.ndarray] = []
    have = 0
    while have < n:
        draw = max(64, int((n - have) * 1.6))
        la = rng.uniform(lat_min, lat_max, draw)
        lo = rng.uniform(-180.0, 180.0, draw)
        ocean = cf.sample(la, lo) > 0.0
        la, lo = la[ocean], lo[ocean]
        lats.append(la)
        lons.append(lo)
        have += int(la.size)
    return np.concatenate(lats)[:n], np.concatenate(lons)[:n]


def _sic_scene_features(
    ice: SeaIceModel, env: EnvironmentModel, lat: np.ndarray, lon: np.ndarray, t0: float
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Analysis-time predictors for one scene, shared by every lead time.

    Returns the lead-independent feature block and the t0 concentration, which doubles as the
    persistence baseline.
    """
    conc0, _ = ice._raw_concentration(lat, lon, t0)

    # Central differences give the local structure of the ice edge and of the floe field, which
    # is what tells the model whether it is standing in the compact pack, inside a lead, or on
    # the gradient at the edge.
    c_n, _ = ice._raw_concentration(lat + _H_LAT_DEG, lon, t0)
    c_s, _ = ice._raw_concentration(lat - _H_LAT_DEG, lon, t0)
    c_e, _ = ice._raw_concentration(lat, lon + _H_LON_DEG, t0)
    c_w, _ = ice._raw_concentration(lat, lon - _H_LON_DEG, t0)
    dconc_dlat = (c_n - c_s) / (2.0 * _H_LAT_DEG)
    dconc_dlon = (c_e - c_w) / (2.0 * _H_LON_DEG)

    u10, v10, _ = env.wind_uv(lat, lon, t0)
    wind_speed = np.hypot(u10, v10)
    uo, vo = env.current_uv(lat, lon, t0)
    scal = env.scalars(lat, lon, t0, wind_speed, conc0)

    drift_u, drift_v = ice.drift_uv(lat, lon, t0)
    div = ice.divergence(lat, lon, t0)
    comp = ice.compression_index(div)

    d_coast = get_coast_field().sample(lat, lon)
    edge = ice.ice_edge_lat(lon, t0)

    doy = env.day_of_year(t0)
    ones = np.ones_like(lat)
    sin_doy = ones * math.sin(2.0 * math.pi * doy / 365.25)
    cos_doy = ones * math.cos(2.0 * math.pi * doy / 365.25)

    block = np.column_stack(
        [
            conc0,
            dconc_dlat,
            dconc_dlon,
            lat,
            lon,
            sin_doy,
            cos_doy,
            u10,
            v10,
            wind_speed,
            uo,
            vo,
            scal["t2m_c"],
            scal["sst_c"],
            drift_u,
            drift_v,
            div,
            comp,
            d_coast,
            edge,
        ]
    )
    return block, conc0


def build_sic_dataset(
    n_samples: int = 60_000,
    lead_hours_list: Sequence[float] = SIC_LEAD_HOURS,
    seed: int = 26_059,
    t0_window: Tuple[float, float] = SIC_TRAIN_WINDOW_H,
    points_per_scene: int = SIC_POINTS_PER_SCENE,
) -> SICDataset:
    """
    Build a sea-ice concentration forecasting dataset.

    Features are the analysis state at t0 (concentration and its gradients, position, season,
    wind, current, temperatures, ice drift, divergence, compression, distance to coast and the
    ice-edge latitude at that longitude) plus the lead time itself. The target is the raw
    concentration analysis valid at t0 + lead, taken from SeaIceModel._raw_concentration.

    SPLITTING IS BY TIME, NOT AT RANDOM. t0 values are drawn only from t0_window, and the three
    windows declared in this module are separated by an embargo equal to the longest lead time.
    A random split would leak: neighbouring rows share one realisation of the floe noise field
    and one synoptic system, so a randomly held-out row is a near-duplicate of a training row and
    the score would measure memorisation rather than forecast skill.

    n_samples is the approximate row count. The realised count is
    n_scenes * points_per_scene * len(lead_hours_list), with n_scenes rounded to at least one.
    """
    ice = get_sea_ice_model()
    env = get_environment()
    leads = [float(lead) for lead in lead_hours_list]
    rng = np.random.default_rng(seed)

    per_scene_rows = max(1, points_per_scene * len(leads))
    n_scenes = max(1, int(round(n_samples / per_scene_rows)))

    # Analysis times spread evenly across the window, with a jitter under the spacing so the
    # model never sees a purely periodic sampling of the synoptic cycle.
    lo, hi = t0_window
    edges = np.linspace(lo, hi, n_scenes, endpoint=False)
    spacing = (hi - lo) / max(1, n_scenes)
    t0_values = edges + rng.uniform(0.0, spacing, n_scenes)

    xs: List[np.ndarray] = []
    ys: List[np.ndarray] = []
    leads_col: List[np.ndarray] = []
    t0_col: List[np.ndarray] = []
    pers: List[np.ndarray] = []
    clim: List[np.ndarray] = []
    phys: List[np.ndarray] = []

    for t0_raw in t0_values:
        t0 = float(t0_raw)
        lat, lon = _ocean_points(rng, points_per_scene)
        block, conc0 = _sic_scene_features(ice, env, lat, lon, t0)

        for lead in leads:
            truth, _ = ice._raw_concentration(lat, lon, t0 + lead)
            forecast, _ = ice._advected_concentration(lat, lon, t0, lead)

            # Climatological baseline: the ice-edge ramp valid at the target time, with no
            # knowledge of today's analysis at all. This is the "what does late December
            # normally look like here" bar, and it is the one a seasonal model has to clear.
            edge_valid = ice.ice_edge_lat(lon, t0 + lead)
            climo = 0.94 * smoothstep(-0.6, 5.5, edge_valid - lat)

            xs.append(np.column_stack([block, np.full_like(lat, lead)]))
            ys.append(truth)
            leads_col.append(np.full_like(lat, lead))
            t0_col.append(np.full_like(lat, t0))
            pers.append(conc0)
            clim.append(np.clip(climo, 0.0, 1.0))
            phys.append(forecast)

    return SICDataset(
        X=np.concatenate(xs).astype(np.float64),
        y=np.concatenate(ys).astype(np.float64),
        feature_names=SIC_FEATURE_NAMES,
        lead_hours=np.concatenate(leads_col),
        t0_hours=np.concatenate(t0_col),
        persistence=np.concatenate(pers),
        climatology=np.concatenate(clim),
        physics=np.concatenate(phys),
        window_hours=(float(lo), float(hi)),
    )


def build_sic_splits(
    n_train: int = 60_000,
    n_val: int = 18_000,
    n_test: int = 24_000,
    lead_hours_list: Sequence[float] = SIC_LEAD_HOURS,
    seed: int = 26_059,
) -> Dict[str, SICDataset]:
    """
    Train, validation and test slices on disjoint, embargoed analysis-time windows.

    Each split gets its own seed stream so that changing one split's size does not perturb the
    contents of the others, which is what lets a quick smoke build be compared against a full
    build without re-deriving everything.
    """
    return {
        "train": build_sic_dataset(n_train, lead_hours_list, seed, SIC_TRAIN_WINDOW_H),
        "val": build_sic_dataset(n_val, lead_hours_list, seed + 1, SIC_VAL_WINDOW_H),
        "test": build_sic_dataset(n_test, lead_hours_list, seed + 2, SIC_TEST_WINDOW_H),
    }


