GROWLER_FEATURE_NAMES: Tuple[str, ...] = (
    "rcs_dbsm",
    "range_nm",
    "sig_wave_height_m",
    "blob_area_px",
    "aspect_ratio",
    "doppler_ms",
    "ice_concentration",
    "snr_db",
)


@dataclass(frozen=True)
class GrowlerDataset:
    """Radar-return features with a binary real-target versus clutter label."""

    X: np.ndarray
    y: np.ndarray
    feature_names: Tuple[str, ...]
    scene_index: np.ndarray

    def __len__(self) -> int:
        return int(self.X.shape[0])

    def as_tuple(self) -> Tuple[np.ndarray, np.ndarray, Tuple[str, ...]]:
        return self.X, self.y, self.feature_names


def build_growler_dataset(
    n_scenes: int = 900,
    seed: int = 26_059,
    max_range_nm: float = 6.0,
) -> GrowlerDataset:
    """
    Build the radar discrimination dataset: real small-ice targets against sea clutter.

    Generated from radar physics rather than sampled from an annotated archive. Within one sweep:

      * Sea state and background ice concentration are drawn per scene, so every return in a
        scene shares its clutter environment. That is why the split is by scene: splitting by
        return would let the classifier read a scene's clutter level off its training rows.
      * Real targets are growlers and bergy bits of waterline length L. Radar cross-section
        scales close to L squared with a Swerling-like lognormal fluctuation for aspect and
        surface wetness. They drift slowly, so radial Doppler is small; they are compact, so blob
        aspect ratio is near unity; blob area falls with range as the beam footprint grows
        relative to the target.
      * Clutter returns are breaking wave crests. Their cross-section rises steeply with
        significant wave height and falls with range as the grazing angle drops, they are
        elongated along the crest so aspect ratio is high, and their orbital velocity gives a
        much wider Doppler spread.
      * Both classes then pass a detection gate: only returns whose signal-to-clutter-plus-noise
        ratio clears a logistic threshold enter the dataset. That is what makes the problem both
        hard and honest. Weak distant growlers are simply absent, exactly as they are on a real
        PPI, and the class balance shifts with sea state instead of being fixed by fiat.

    The label is 1 for a real ice target and 0 for clutter.
    """
    rng = np.random.default_rng(seed)
    n_scenes = max(1, int(n_scenes))

    feats: List[np.ndarray] = []
    labels: List[np.ndarray] = []
    scenes: List[np.ndarray] = []

    for scene in range(n_scenes):
        hs = float(np.clip(rng.gamma(2.2, 1.1), 0.15, 9.0))
        ice_conc = float(np.clip(rng.beta(1.6, 2.0), 0.0, 1.0))

        # Ice cover makes real targets more numerous and damps the sea, so clutter density falls
        # as concentration rises. This is the correlation that makes ice_concentration a genuine
        # predictor rather than a decorative feature.
        n_target = int(rng.poisson(2.0 + 9.0 * ice_conc))
        n_clutter = int(
            rng.poisson(
                1.0 + 16.0 * min(1.0, hs / RADAR_CLUTTER_WAVE_HEIGHT_M) * (1.0 - 0.7 * ice_conc)
            )
        )
        if n_target + n_clutter == 0:
            continue

        # --- real ice targets ---------------------------------------------------------------
        # Uniform area density means range is distributed as the square root of a uniform draw.
        rng_t = max_range_nm * np.sqrt(rng.uniform(0.0, 1.0, n_target))
        length_t = np.exp(rng.normal(math.log(4.5), 0.65, n_target))
        rcs_t = np.exp(rng.normal(0.0, 0.55, n_target)) * length_t ** 1.9
        doppler_t = rng.normal(0.0, 0.45, n_target)
        aspect_t = 1.0 + np.abs(rng.normal(0.0, 0.45, n_target))
        area_t = np.maximum(
            1.0,
            26.0 * (length_t / 6.0) ** 1.4 / (1.0 + rng_t) * np.exp(rng.normal(0.0, 0.3, n_target)),
        )

        # --- sea clutter --------------------------------------------------------------------
        rng_c = max_range_nm * np.sqrt(rng.uniform(0.0, 1.0, n_clutter))
        rcs_c = np.exp(rng.normal(0.0, 0.9, n_clutter)) * 3.2 * (hs ** 2.1)
        rcs_c = rcs_c * np.exp(-rng_c / 3.4)
        doppler_c = rng.normal(0.0, 0.55 + 0.62 * hs, n_clutter)
        aspect_c = 1.4 + np.abs(rng.normal(1.5, 1.1, n_clutter))
        area_c = np.maximum(
            1.0,
            9.0 * (1.0 + 0.9 * hs) * np.exp(rng.normal(0.0, 0.55, n_clutter)) / (1.0 + 0.4 * rng_c),
        )

        rcs = np.concatenate([rcs_t, rcs_c])
        rng_nm = np.concatenate([rng_t, rng_c])
        doppler = np.concatenate([doppler_t, doppler_c])
        aspect = np.concatenate([aspect_t, aspect_c])
        area = np.concatenate([area_t, area_c])
        label = np.concatenate([np.ones(n_target), np.zeros(n_clutter)])

        # Detection gate. Received power falls as the fourth power of range; the clutter floor
        # rises with sea state. Only returns that clear the threshold appear on the display.
        rcs_dbsm = 10.0 * np.log10(np.maximum(rcs, 1e-4))
        clutter_floor_db = -14.0 + 9.5 * math.log10(1.0 + hs)
        snr_db = rcs_dbsm - 40.0 * np.log10(np.maximum(rng_nm, 0.05)) + 26.0 - clutter_floor_db
        p_det = 1.0 / (1.0 + np.exp(-(snr_db - 6.0) / 3.0))
        detected = rng.uniform(0.0, 1.0, snr_db.size) < p_det
        n_det = int(detected.sum())
        if n_det == 0:
            continue

        feats.append(
            np.column_stack(
                [
                    rcs_dbsm[detected],
                    rng_nm[detected],
                    np.full(n_det, hs),
                    area[detected],
                    aspect[detected],
                    doppler[detected],
                    np.full(n_det, ice_conc),
                    snr_db[detected],
                ]
            )
        )
        labels.append(label[detected])
        scenes.append(np.full(n_det, scene))

    return GrowlerDataset(
        X=np.concatenate(feats).astype(np.float64),
        y=np.concatenate(labels).astype(np.int64),
        feature_names=GROWLER_FEATURE_NAMES,
        scene_index=np.concatenate(scenes).astype(np.int64),
    )


def split_growler_dataset(
    ds: GrowlerDataset, train_frac: float = 0.6, val_frac: float = 0.15
) -> Dict[str, GrowlerDataset]:
    """
    Split by scene, never by return.

    Two returns from the same sweep share a sea state and an ice concentration, both of which are
    features. Splitting by row would put a training scene's clutter environment into the test
    set, and the classifier would be scoring itself on conditions it had already been shown.
    Scenes are generated in time order, so this is also a forward-in-time split.
    """
    scenes = np.unique(ds.scene_index)
    n = int(scenes.size)
    n_train = int(round(n * train_frac))
    n_val = int(round(n * val_frac))
    bounds = {
        "train": scenes[:n_train],
        "val": scenes[n_train : n_train + n_val],
        "test": scenes[n_train + n_val :],
    }
    out: Dict[str, GrowlerDataset] = {}
    for name, keep in bounds.items():
        m = np.isin(ds.scene_index, keep)
        out[name] = GrowlerDataset(
            X=ds.X[m],
            y=ds.y[m],
            feature_names=ds.feature_names,
            scene_index=ds.scene_index[m],
        )
    return out
