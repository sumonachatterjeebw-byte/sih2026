"""
Supervised dataset construction from the project's own physics environment.

WHERE THE DATA COMES FROM, STATED PLAINLY (build spec P2). There is no observational archive in
this repository. Every row produced here is generated by running the modules in src/core against
seeded, physically-structured synthetic fields. That is a real dataset in the sense that it has
spatial correlation, a seasonal cycle, advective memory, noise and an irreducible error floor -
it is not random numbers - but it is not satellite data, and no metric derived from it may be
presented as operational skill.

The three builders here are deliberately shaped so that the same code trains on real products
once a NetCDF loader replaces the physics sampler. The feature vectors are exactly the fields an
operator would have from OSI-SAF, AMSR2, ERA5 and CMEMS; see docs/ML_MODELS.md.

DETERMINISM (build spec P3). Every builder takes a seed and uses numpy Generator streams only.
Calling a builder twice with the same arguments returns bit-identical arrays.
"""
