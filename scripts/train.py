# Iceberg drift residual
# --------------------------------------------------------------------------------------
def train_drift(sizes: Dict[str, int], seed: int) -> Dict[str, Any]:
    _rule("2. Iceberg drift residual corrector")
    t_data = time.perf_counter()
    splits = ds_mod.build_drift_splits(
        n_train=sizes["drift_train"],
        n_val=sizes["drift_val"],
        n_test=sizes["drift_test"],
        seed=seed,
    )
    data_s = time.perf_counter() - t_data
    print(
        f"   dataset  train {len(splits['train']):>6d} rows "
        f"({sizes['drift_train']} bergs)  val {len(splits['val']):>5d}  "
        f"test {len(splits['test']):>5d}   ({data_s:.1f} s)"
    )
    print(
        f"   split    disjoint bergs on disjoint t0 windows "
        f"{ds_mod.DRIFT_TRAIN_WINDOW_H} / {ds_mod.DRIFT_VAL_WINDOW_H} / {ds_mod.DRIFT_TEST_WINDOW_H} h"
    )

    t_fit = time.perf_counter()
    model = DriftResidualModel(random_state=seed).fit(splits["train"], splits["val"])
    fit_s = time.perf_counter() - t_fit
    print(f"   fitted   {model.estimator_kind} selected on the validation split  ({fit_s:.1f} s)")
    for entry in model.metadata["estimator_selection"]:
        mark = "*" if entry["selected"] else " "
        print(f"            {mark} {entry['estimator']:<6s} val residual RMSE {_fmt(entry['val_residual_rmse_ms'], 9, 5)} m/s")

    test_metrics = model.evaluate(splits["test"])
    pos = test_metrics["position_error"]
    print()
    print(
        f"   Velocity residual on held-out bergs: RMSE {test_metrics['residual_rmse_ms']:.5f} m/s "
        f"against {test_metrics['uncorrected_residual_rmse_ms']:.5f} m/s uncorrected "
        f"({100.0 * test_metrics['residual_variance_explained']:.1f} percent of residual variance explained)."
    )
    print()
    print(f"   {pos['horizon_hours']:.0f}-hour position error against the observed track, {pos['n_bergs']} held-out bergs:")
    print("                                   mean      median        p90        max")
    for label, key in (
        ("physics only  (Euler)", "physics_euler"),
        ("physics + residual   ", "physics_plus_residual"),
        ("physics only  (RK4)  ", "physics_rk4_reference"),
    ):
        block = pos[key]
        print(
            f"   {label}  {block['mean_km']:>9.3f} km {block['median_km']:>9.3f} km"
            f" {block['p90_km']:>9.3f} km {block['max_km']:>8.2f} km"
        )
    print(
        f"   improvement: {pos['mean_improvement_km']:+.3f} km on the mean "
        f"({pos['mean_improvement_percent']:+.1f} percent), "
        f"{pos['median_improvement_percent']:+.1f} percent on the median; "
        f"{100.0 * pos['bergs_improved_fraction']:.0f} percent of bergs improved."
    )
    if pos["mean_improvement_percent"] <= 0.0:
        print("   HONEST NOTE: the residual corrector does NOT improve the mean 72-hour position error.")

    path = model.save(Path(MODELS_DIR) / DRIFT_ARTEFACT_NAME)
    print(f"   saved    {path.name}  ({path.stat().st_size / 1024:.0f} KB)")

    return {
        "task": "Correct the velocity error of the RK4 iceberg momentum balance",
        "estimator": model.estimator_kind,
        "artefact": path.name,
        "claim": model.metadata["claim"],
        "feature_names": list(model.feature_names),
        "target_names": list(model.target_names),
        "estimator_selection": model.metadata["estimator_selection"],
        "dataset": {
            "n_train_rows": len(splits["train"]),
            "n_val_rows": len(splits["val"]),
            "n_test_rows": len(splits["test"]),
            "n_train_bergs": sizes["drift_train"],
            "n_val_bergs": sizes["drift_val"],
            "n_test_bergs": sizes["drift_test"],
            "forecast_hours": ds_mod.DRIFT_FORECAST_HOURS,
            "output_interval_hours": ds_mod.DRIFT_OUTPUT_INTERVAL_H,
            "split_kind": "disjoint bergs on disjoint time windows",
            "train_window_hours": list(ds_mod.DRIFT_TRAIN_WINDOW_H),
            "val_window_hours": list(ds_mod.DRIFT_VAL_WINDOW_H),
            "test_window_hours": list(ds_mod.DRIFT_TEST_WINDOW_H),
            "generation_seconds": round(data_s, 2),
        },
        "fit_seconds": round(fit_s, 2),
        "val": model.evaluate(splits["val"]),
        "test": test_metrics,
        "headline": {
            "physics_mean_position_error_km": pos["physics_euler"]["mean_km"],
            "corrected_mean_position_error_km": pos["physics_plus_residual"]["mean_km"],
            "mean_improvement_percent": pos["mean_improvement_percent"],
            "median_improvement_percent": pos["median_improvement_percent"],
        },
    }


