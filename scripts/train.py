# Growler classifier
# --------------------------------------------------------------------------------------
def train_growler(sizes: Dict[str, int], seed: int) -> Dict[str, Any]:
    _rule("3. Growler versus sea-clutter classifier")
    t_data = time.perf_counter()
    full = ds_mod.build_growler_dataset(n_scenes=sizes["growler_scenes"], seed=seed)
    splits = ds_mod.split_growler_dataset(full)
    data_s = time.perf_counter() - t_data
    print(
        f"   dataset  {len(full)} returns from {sizes['growler_scenes']} sweeps, "
        f"{100.0 * float(np.mean(full.y)):.1f} percent real targets   ({data_s:.1f} s)"
    )
    print(
        f"   split    by sweep, not by return: train {len(splits['train'])}  "
        f"val {len(splits['val'])}  test {len(splits['test'])} returns"
    )

    t_fit = time.perf_counter()
    model = GrowlerClassifier(random_state=seed).fit(splits["train"], splits["val"])
    fit_s = time.perf_counter() - t_fit
    print(f"   fitted   RandomForestClassifier {model.hyperparameters}  ({fit_s:.1f} s)")

    test_metrics = model.evaluate(splits["test"])
    m = test_metrics["model"]
    cm = test_metrics["confusion_matrix"]
    snr = test_metrics["baselines"]["snr_threshold"]
    majority = test_metrics["baselines"]["majority_class"]
    print()
    print("   Held-out TEST sweeps.")
    print("                        accuracy  precision     recall         F1    ROC-AUC")
    print(
        f"   random forest        {m['accuracy']:>9.4f} {m['precision']:>10.4f}"
        f" {m['recall']:>10.4f} {m['f1']:>10.4f} {m.get('roc_auc', float('nan')):>10.4f}"
    )
    print(
        f"   SNR threshold base   {snr['accuracy']:>9.4f} {snr['precision']:>10.4f}"
        f" {snr['recall']:>10.4f} {snr['f1']:>10.4f} {snr.get('roc_auc', float('nan')):>10.4f}"
        f"   (cut {snr['threshold_dB']:.2f} dB)"
    )
    print(
        f"   majority class base  {majority['accuracy']:>9.4f} {majority['precision']:>10.4f}"
        f" {majority['recall']:>10.4f} {majority['f1']:>10.4f}"
    )
    print()
    print("   Confusion matrix (rows: truth, columns: predicted)")
    print(f"                 clutter   ice_target")
    print(f"   clutter    {cm['true_negative']:>9d} {cm['false_positive']:>12d}")
    print(f"   ice_target {cm['false_negative']:>9d} {cm['true_positive']:>12d}")
    if m["f1"] <= snr["f1"]:
        print()
        print("   HONEST NOTE: the forest does NOT beat the single SNR-threshold baseline on F1.")

    path = model.save(Path(MODELS_DIR) / GROWLER_ARTEFACT_NAME)
    print(f"   saved    {path.name}  ({path.stat().st_size / 1024:.0f} KB)")

    return {
        "task": "Classify a radar blob as a real ice target or sea clutter",
        "estimator": "RandomForestClassifier",
        "artefact": path.name,
        "hyperparameters": model.hyperparameters,
        "feature_names": list(model.feature_names),
        "feature_importances": model.metadata["feature_importances"],
        "snr_threshold_dB": model.metadata["snr_threshold_dB"],
        "dataset": {
            "n_scenes": sizes["growler_scenes"],
            "n_returns_total": len(full),
            "n_train_rows": len(splits["train"]),
            "n_val_rows": len(splits["val"]),
            "n_test_rows": len(splits["test"]),
            "positive_fraction": round(float(np.mean(full.y)), 5),
            "split_kind": "by sweep (scene), forward in generation order",
            "generation_seconds": round(data_s, 2),
        },
        "fit_seconds": round(fit_s, 2),
        "val": model.evaluate(splits["val"]),
        "test": test_metrics,
        "headline": {
            "test_f1": m["f1"],
            "test_roc_auc": m.get("roc_auc"),
            "snr_baseline_f1": snr["f1"],
        },
    }


# --------------------------------------------------------------------------------------
def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train the POLAR-NAV AI machine-learning layer.")
    parser.add_argument("--quick", action="store_true", help="small smoke run, well under a minute")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help="master seed for everything")
    parser.add_argument(
        "--only",
        choices=["sic", "drift", "growler"],
        action="append",
        help="train only the named model; may be repeated",
    )
    args = parser.parse_args(argv)

    sizes = QUICK if args.quick else FULL
    wanted = set(args.only) if args.only else {"sic", "drift", "growler"}

    Path(MODELS_DIR).mkdir(parents=True, exist_ok=True)

    print("=" * 92)
    print("POLAR-NAV AI  -  machine-learning layer training")
    print("=" * 92)
    print(f"  mode          {'quick smoke run' if args.quick else 'full run'}")
    print(f"  seed          {args.seed}")
    print(f"  python        {platform.python_version()}   scikit-learn {sklearn.__version__}   numpy {np.__version__}")
    print(f"  models dir    {MODELS_DIR}")
    print()
    print("  DATA PROVENANCE. Every row is generated by this repository's synthetic physics")
    print("  environment. All metrics below are simulated-environment metrics, not operational")
    print("  skill against OSI-SAF, AMSR2, ERA5 or CMEMS. See docs/ML_MODELS.md.")

    started = time.perf_counter()
    models: Dict[str, Any] = {}
    if "sic" in wanted:
        models["sic_forecaster"] = train_sic(sizes, args.seed)
    if "drift" in wanted:
        models["drift_residual"] = train_drift(sizes, args.seed)
    if "growler" in wanted:
        models["growler_classifier"] = train_growler(sizes, args.seed)
    wall = time.perf_counter() - started

    payload = {
        "system": "POLAR-NAV AI",
        "problem_statement": "26059",
        "trained_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "training_wall_time_s": round(wall, 2),
        "mode": "quick" if args.quick else "full",
        "seed": args.seed,
        "python_version": platform.python_version(),
        "sklearn_version": sklearn.__version__,
        "numpy_version": np.__version__,
        "data_provenance": (
            "Synthetic. Datasets are generated by src/core/environment.py, src/core/sea_ice.py "
            "and src/core/iceberg_tracker.py, which stand in for ERA5/CMEMS forcing, "
            "OSI-SAF/AMSR2 concentration and USNIC/BYU iceberg tracks respectively. All metrics "
            "in this file are simulated-environment metrics and must not be presented as "
            "operational forecast skill."
        ),
        "retrain_on_real_data": "See the 'How to retrain on real data' section of docs/ML_MODELS.md.",
        "models": models,
    }

    path = metrics_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, sort_keys=False)
        fh.write("\n")

    _rule("Summary")
    for key, record in models.items():
        print(f"   {key:<20s} {record['estimator']:<32s} {json.dumps(record['headline'])}")
    print()
    print(f"   metrics written to {path}")
    print(f"   total wall time    {wall:.1f} s")
    print("=" * 92)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
