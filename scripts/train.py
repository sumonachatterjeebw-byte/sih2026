# Sea-ice concentration forecaster
# --------------------------------------------------------------------------------------
def train_sic(sizes: Dict[str, int], seed: int) -> Dict[str, Any]:
    _rule("1. Sea-ice concentration forecaster")
    t_data = time.perf_counter()
    splits = ds_mod.build_sic_splits(
        n_train=sizes["sic_train"],
        n_val=sizes["sic_val"],
        n_test=sizes["sic_test"],
        seed=seed,
    )
    data_s = time.perf_counter() - t_data
    print(
        f"   dataset  train {len(splits['train']):>6d} rows  "
        f"val {len(splits['val']):>6d}  test {len(splits['test']):>6d}   ({data_s:.1f} s)"
    )
    print(
        "   split    train t0 "
        f"{ds_mod.SIC_TRAIN_WINDOW_H}  val t0 {ds_mod.SIC_VAL_WINDOW_H}  "
        f"test t0 {ds_mod.SIC_TEST_WINDOW_H}  hours; "
        f"embargo {ds_mod.SIC_EMBARGO_H:.0f} h between windows"
    )

    t_fit = time.perf_counter()
    model = SICForecaster(random_state=seed).fit(splits["train"], splits["val"])
    fit_s = time.perf_counter() - t_fit
    print(f"   fitted   HistGradientBoostingRegressor {model.hyperparameters}  ({fit_s:.1f} s)")

    test_metrics = model.evaluate(splits["test"])
    val_metrics = model.evaluate(splits["val"])

    print()
    print("   Held-out TEST split, RMSE of concentration (0-1). Lower is better.")
    print("   lead_h        n       ML  persist    clim  physics |  skill vs persist   clim  physics")
    for row in test_metrics["per_lead"]:
        base = row["baselines"]
        skill = row["skill_score_vs"]
        print(
            f"   {row['lead_hours']:>6.0f} {row['n_samples']:>8d}"
            f" {row['model']['rmse']:>8.4f} {base['persistence']['rmse']:>8.4f}"
            f" {base['climatology']['rmse']:>7.4f} {base['physics']['rmse']:>8.4f} |"
            f" {skill['persistence']:>+9.3f} {skill['climatology']:>+7.3f} {skill['physics']:>+8.3f}"
        )
    overall = test_metrics["overall"]
    print(
        f"   {'all':>6} {overall['n_samples']:>8d}"
        f" {overall['model']['rmse']:>8.4f} {overall['baselines']['persistence']['rmse']:>8.4f}"
        f" {overall['baselines']['climatology']['rmse']:>7.4f}"
        f" {overall['baselines']['physics']['rmse']:>8.4f} |"
        f" {overall['skill_score_vs']['persistence']:>+9.3f}"
        f" {overall['skill_score_vs']['climatology']:>+7.3f}"
        f" {overall['skill_score_vs']['physics']:>+8.3f}"
    )
    print()
    print("   Ice-edge agreement (IIEE, fraction of samples on the wrong side of 15 percent).")
    print("   lead_h       ML  persist     clim  physics       R2       MAE")
    for row in test_metrics["per_lead"]:
        base = row["baselines"]
        print(
            f"   {row['lead_hours']:>6.0f} {row['model']['iiee_fraction']:>8.4f}"
            f" {base['persistence']['iiee_fraction']:>8.4f}"
            f" {base['climatology']['iiee_fraction']:>8.4f}"
            f" {base['physics']['iiee_fraction']:>8.4f}"
            f" {row['model']['r2']:>8.4f} {row['model']['mae']:>9.4f}"
        )

    losses = [r["lead_hours"] for r in test_metrics["per_lead"] if r["skill_score_vs"]["physics"] <= 0.0]
    if losses:
        print()
        print(
            "   HONEST NOTE: the learned model does NOT beat the physics forecast at lead "
            + ", ".join(f"{h:.0f} h" for h in losses)
            + "."
        )

    path = model.save(Path(MODELS_DIR) / SIC_ARTEFACT_NAME)
    print(f"   saved    {path.name}  ({path.stat().st_size / 1024:.0f} KB)")

    return {
        "task": "Forecast sea-ice concentration at t0 + lead from the analysis state at t0",
        "estimator": "HistGradientBoostingRegressor",
        "artefact": path.name,
        "hyperparameters": model.hyperparameters,
        "hyperparameter_selection": model.metadata["hyperparameter_selection"],
        "feature_names": list(model.feature_names),
        "target": "concentration at t0 + lead, from SeaIceModel._raw_concentration",
        "lead_hours": list(ds_mod.SIC_LEAD_HOURS),
        "dataset": {
            "n_train_rows": len(splits["train"]),
            "n_val_rows": len(splits["val"]),
            "n_test_rows": len(splits["test"]),
            "points_per_scene": ds_mod.SIC_POINTS_PER_SCENE,
            "latitude_range": list(ds_mod.SIC_LAT_RANGE),
            "split_kind": "time-based, embargoed",
            "embargo_hours": ds_mod.SIC_EMBARGO_H,
            "train_window_hours": list(ds_mod.SIC_TRAIN_WINDOW_H),
            "val_window_hours": list(ds_mod.SIC_VAL_WINDOW_H),
            "test_window_hours": list(ds_mod.SIC_TEST_WINDOW_H),
            "generation_seconds": round(data_s, 2),
        },
        "fit_seconds": round(fit_s, 2),
        "val": val_metrics,
        "test": test_metrics,
        "headline": {
            "test_rmse": overall["model"]["rmse"],
            "skill_vs_persistence": overall["skill_score_vs"]["persistence"],
            "skill_vs_climatology": overall["skill_score_vs"]["climatology"],
            "skill_vs_physics": overall["skill_score_vs"]["physics"],
            "leads_losing_to_physics": losses,
        },
    }


